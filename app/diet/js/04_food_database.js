// ── FOOD_DB INTEGRITY VALIDATOR ──────────────────────────────────────
// Detects duplicate IDs silently — duplicate entries cause FOOD_MAP to
// silently overwrite macros and medical flags with the last entry.
// Runs once at init; logs warnings to console only (no user impact).
(function _validateFoodDbIntegrity() {
  try {
    const seen = new Map();
    const dups = [];
    for (const food of FOOD_DB) {
      if (!food || !food.id) { LOG('FOOD_DB: entry missing id'); continue; }
      if (seen.has(food.id)) {
        dups.push(food.id);
        // Keep FIRST occurrence in FOOD_MAP (re-insert to ensure first wins)
        if (!FOOD_MAP.has(food.id + '__dup_checked__')) {
          FOOD_MAP.set(food.id, seen.get(food.id)); // restore first entry
        }
      } else {
        seen.set(food.id, food);
      }
    }
    if (dups.length > 0) {
      console.warn(`FOOD_DB: ${dups.length} duplicate ID(s) detected — first entry preserved in FOOD_MAP:`, dups);
      LOG(`FOOD_DB integrity: ${dups.length} duplicate IDs - ${dups.join(', ')}`);
    } else {
      LOG(`✔ FOOD_DB integrity: all ${FOOD_DB.length} IDs unique`);
    }
  } catch(e) { LOG('FOOD_DB validator error: ' + e.message); }
})();
// ── END FOOD_DB INTEGRITY VALIDATOR ──────────────────────────────────

