const FoodStorage = {
  STORAGE_KEY: 'dietEngine_foodDB_v4',
  load() {
    try {
      if (typeof localStorage === 'undefined') return null;
      const saved = localStorage.getItem(this.STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length > 0) {
          LOG(`✔ Loaded ${parsed.length} custom foods from localStorage`);
          return parsed;
        }
      }
    } catch(e) { LOG('localStorage load failed (expected in some envs): ' + e.message); }
    return null;
  },
  save(db) {
    try {
      if (typeof localStorage === 'undefined') return;
      localStorage.setItem(this.STORAGE_KEY, JSON.stringify(db));
      LOG(`✔ Saved ${db.length} foods to localStorage`);
    } catch(e) { LOG('localStorage save failed: ' + e.message); }
  }
};

