      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Padding(
          padding: const EdgeInsets.fromLTRB(4, 14, 4, 8),
          child: Row(children: [
            Icon(section.icon, color: section.color, size: 20),
            const SizedBox(width: 8),
            Text(section.title,
