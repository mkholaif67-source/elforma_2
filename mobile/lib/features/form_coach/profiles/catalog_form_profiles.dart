import 'package:elforma/features/form_coach/domain/rep_cycle.dart';

FormProfile _catalogTracking(
    String id,
    String title,
    List<String> names,
    List<FcJoint> joints,
    double top,
    double bottom,
    String topLabel,
    String bottomLabel,
    {MetricKind kind = MetricKind.jointAngle}) {
  return FormProfile(
    id: id,
    titleAr: title,
    supportLevel: FormSupportLevel.trackingOnly,
    setupHintAr: 'ثبّت الهاتف وأظهر المفاصل المطلوبة بالكامل',
    detectableAr: <String>['العداد التقريبي', 'مرحلة الحركة', 'المدى الظاهر'],
    notDetectableAr: <String>[
      'الوزن والقبضة',
      'شد العضلة والتنفس',
      'التفاصيل خارج زاوية التصوير'
    ],
    matchKeywords: names,
    completion: const CompletionSpec(fallbackTargetReps: 10),
    variants: <FormProfileVariant>[
      FormProfileVariant(
        id: '$id.default',
        titleAr: '$title - متابعة الحركة',
        supportLevel: FormSupportLevel.trackingOnly,
        readiness: ReadinessSpec(
            requiredJoints: joints,
            minTorsoFraction: 0.08,
            maxTorsoFraction: 0.85),
        sideSelection: SideSelection.activeSide,
        sideAmplitudeMetrics: const ['motion_left', 'motion_right'],
        metrics: <MetricSpec>[
          for (final entry in {
            'motion_left': MetricSide.left,
            'motion_right': MetricSide.right
          }.entries)
            MetricSpec(
                id: entry.key,
                kind: kind,
                side: entry.value,
                joints: kind == MetricKind.limbAbductionFromTorso
                    ? joints.sublist(0, 2)
                    : joints.sublist(0, 3)),
          MetricSpec(
            id: 'movement_angle',
            kind: kind,
            joints: kind == MetricKind.limbAbductionFromTorso
                ? joints.sublist(0, 2)
                : joints.sublist(0, 3),
            side: MetricSide.activeSide,
            labelAr: 'زاوية الحركة',
          )
        ],
        repCycle: RepCycleSpec(
            driverMetricId: 'movement_angle',
            topValue: top,
            bottomValue: bottom,
            enterMargin: 18,
            minAmplitude: 30,
            partialAmplitude: 18,
            topLabelAr: topLabel,
            bottomLabelAr: bottomLabel),
        driverMinConfidence: 0.52,
      ),
    ],
  );
}

