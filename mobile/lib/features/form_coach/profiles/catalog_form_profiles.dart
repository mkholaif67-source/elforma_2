// Catalog movement-family profiles. These are deliberately tracking-only.
// They count visible movement and phases but do not claim full form correction.
import 'package:elforma/features/form_coach/domain/fc_landmarks.dart';
import 'package:elforma/features/form_coach/domain/form_profile.dart';
